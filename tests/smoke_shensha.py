def check(cond: bool, label: str) -> None:
    if cond:
        print(f"  {OK} {label}")
    else:
        print(f"  [FAIL] {label}")
        FAIL.append(label)


def mk(gans, zhis, gender="男", nayin="海中金", day_pillar=None):
    g = dict(zip(("年柱", "月柱", "日柱", "时柱"), gans))
    z = dict(zip(("年柱", "月柱", "日柱", "时柱"), zhis))
    return build_shen_sha(g, z, day_pillar or (g["日柱"] + z["日柱"]),
                          gender=gender, year_nayin=nayin)


def has(res, pillar: str, name: str) -> bool:
    return name in res["按柱分布"][pillar]


def all_names(res) -> set:
    return {n.replace("(日支查)", "") for v in res["按柱分布"].values() for n in v}



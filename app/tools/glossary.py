@tool
def explain_term(term: str) -> str:
    """解释命理术语。用户问"什么是XX""XX是什么意思"时使用，返回白话释义。

    词典覆盖十神、格局、神煞、大运流年、六爻、黄历常用术语，支持模糊匹配。

    Args:
        term: 要解释的术语，如 "伤官"、"用神"、"世应"
    """
    key = (term or "").strip().replace(" ", "")
    if not key:
        return json.dumps({"错误": "请提供要解释的术语"}, ensure_ascii=False)

    if key in GLOSSARY:
        return json.dumps({"术语": key, "释义": GLOSSARY[key]},
                          ensure_ascii=False, indent=2)

    hits: List[str] = [k for k in GLOSSARY if key in k or k in key]
    if not hits:
        return json.dumps(
            {"术语": key, "释义": None,
             "提示": "词典未收录该词，可按字面所属体系（十神/神煞/六爻/黄历）说明，并注明非标准术语"},
            ensure_ascii=False,
        )
    hits = sorted(hits, key=len)[:5]
    return json.dumps(
        {"术语": key, "匹配": [{"术语": h, "释义": GLOSSARY[h]} for h in hits]},
        ensure_ascii=False, indent=2,
    )
